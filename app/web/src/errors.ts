export function errorMessage(err: unknown, t: (s: string) => string): string {
  if (err instanceof ApiError) {
    const msg = MESSAGES[err.code];
    if (msg) return t(msg);
    if (err.code.endsWith('_not_found')) return t(MESSAGES.not_found);
    if (err.code.startsWith('invalid_') || err.code.endsWith('_required')) return t(MESSAGES.validation_failed);
    if (err.code.startsWith('oidc_')) return t('Logowanie firmowe nie powiodło się. Spróbuj ponownie.');
    return t('Wystąpił błąd: {code}').replace('{code}', err.code);
  }
  return t(MESSAGES.internal_error);
}

export function errorCode(err: unknown): string | undefined {
  return err instanceof ApiError ? err.code : undefined;
}
